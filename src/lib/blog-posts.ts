const BLOG_TOPICS: Record<BlogSlug, BlogTopicConfig> = {
  'implant-guide': IMPLANT_GUIDE,
  'wisdom-tooth-guide': WISDOM_TOOTH_GUIDE,
  'cavity-resin': CAVITY_RESIN,
  'cavity-inlay': CAVITY_INLAY,
  'cavity-crown': CAVITY_CROWN,
};

export function getBlogTopic(slug: BlogSlug): BlogTopicConfig {
  return BLOG_TOPICS[slug];
}

export function getAllBlogTopics(): BlogTopicConfig[] {
  return BLOG_SLUGS.map((s) => BLOG_TOPICS[s]);
}

export interface BlogPostMeta {
  title: string;
  description: string;
  keywords: string[];
  canonical: string;
  shortLabel: string;
  category: string;
  treatmentType: 'implant' | 'cavity-treatment' | 'wisdom-tooth';
}

export function buildBlogArticleData(
  regionName: string,
  regionSlug: string,
  slug: BlogSlug,
): RegionArticleData {
  const topic = BLOG_TOPICS[slug];
  return {
    regionName,
    regionSlug,
    treatmentType: topic.treatmentType,
    title: topic.titleFn(regionName),
    subtitle: topic.subtitle,
    sections: topic.sections,
    tips: topic.tips,
    conclusion: topic.conclusionFn(regionName),
    faqs: topic.faqs,
  };
}

export function buildBlogMeta(
  regionName: string,
  regionSlug: string,
  slug: BlogSlug,
): BlogPostMeta {
  const topic = BLOG_TOPICS[slug];
  return {
    title: topic.metaTitleFn(regionName),
    description: topic.metaDescriptionFn(regionName),
    keywords: topic.keywordsFn(regionName),
    canonical: `https://gdfirstdent.co.kr/${regionSlug}/blog/${slug}`,
    shortLabel: topic.shortLabel,
    category: topic.category,
    treatmentType: topic.treatmentType,
  };
}

export function buildBlogMetadata(
  regionName: string,
  regionSlug: string,
  slug: BlogSlug,
): Metadata {
  const meta = buildBlogMeta(regionName, regionSlug, slug);
  return {
    title: meta.title,
    description: meta.description,
    keywords: meta.keywords,
    alternates: {
      canonical: meta.canonical,
    },
    openGraph: {
      title: meta.title,
      description: meta.description,
      url: meta.canonical,
      siteName: '고덕퍼스트치과',
      type: 'article',
      images: [
        {
          url: '/고덕og이미지.png',
          width: 1200,
          height: 630,
          alt: meta.title,
        },
      ],
    },
  };
}

export function buildBlogFaqJsonLd(faqs: { question: string; answer: string }[]) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: faqs.map((faq) => ({
      '@type': 'Question',
      name: faq.question,
      acceptedAnswer: { '@type': 'Answer', text: faq.answer },
    })),
  };
}

export function buildBlogBreadcrumbJsonLd(
  regionName: string,
  regionSlug: string,
  slug: BlogSlug,
  postTitle: string,
) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: '홈', item: 'https://gdfirstdent.co.kr' },
      {
        '@type': 'ListItem',
        position: 2,
        name: regionName,
        item: `https://gdfirstdent.co.kr/${regionSlug}`,
      },
      {
        '@type': 'ListItem',
        position: 3,
        name: postTitle,
        item: `https://gdfirstdent.co.kr/${regionSlug}/blog/${slug}`,
      },
    ],
  };
}

export function isBlogSlug(value: string): value is BlogSlug {
  return (BLOG_SLUGS as string[]).includes(value);
}
